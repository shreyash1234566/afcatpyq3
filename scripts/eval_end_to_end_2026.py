"""
Evaluate the generated 2026 mock paper against the ACTUAL 2026 exam paper.
Uses the same BM25 + Template Match (topic-filtered) metric that we used for 2024.
"""
import json
import math
import sys
from pathlib import Path
from collections import defaultdict

ROOT = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(ROOT))

try:
    from rank_bm25 import BM25Okapi
except ImportError:
    # Minimal BM25 implementation if library not installed
    class BM25Okapi:
        def __init__(self, corpus):
            self.corpus_size = len(corpus)
            self.avgdl = sum(map(len, corpus)) / self.corpus_size
            self.doc_freqs = []
            self.idf = {}
            self.doc_len = []
            
            for document in corpus:
                self.doc_len.append(len(document))
                frequencies = {}
                for word in document:
                    frequencies[word] = frequencies.get(word, 0) + 1
                self.doc_freqs.append(frequencies)
                for word in frequencies.keys():
                    self.idf[word] = self.idf.get(word, 0) + 1
                    
            for word, freq in self.idf.items():
                self.idf[word] = math.log(1 + (self.corpus_size - freq + 0.5) / (freq + 0.5))

        def get_scores(self, query):
            scores = [0.0] * self.corpus_size
            k1, b = 1.5, 0.75
            for q in query:
                q_idf = self.idf.get(q, 0)
                if q_idf == 0: continue
                for i, doc in enumerate(self.doc_freqs):
                    f = doc.get(q, 0)
                    scores[i] += q_idf * (f * (k1 + 1)) / (f + k1 * (1 - b + b * self.doc_len[i] / self.avgdl))
            return scores

def tokenize(text):
    import re
    text = re.sub(r'[^a-z0-9\s]', '', str(text).lower())
    return text.split()

def extract_template(text):
    words = tokenize(text)
    return " ".join(words[:4]) if len(words) >= 4 else " ".join(words)

def main():
    ACTUAL_JSON = ROOT / "data" / "papers" / "afcat_2026_questions.json"
    GENERATED_JSON = ROOT / "output" / "generated_questions" / "practice_2026_sota.json"
    REPORT_PATH = ROOT / "output" / "evaluation" / "eval_e2e_2026_report.json"
    
    if not ACTUAL_JSON.exists():
        print(f"ERROR: {ACTUAL_JSON.name} not found. Please run classify_2026_topics.py first.")
        return
        
    actual_qs = json.loads(ACTUAL_JSON.read_text(encoding="utf-8"))
    generated_qs = json.loads(GENERATED_JSON.read_text(encoding="utf-8"))
    
    print(f"Loaded {len(actual_qs)} actual 2026 questions.")
    print(f"Loaded {len(generated_qs)} generated 2026 mock questions.")
    
    # Group generated by topic for filtering
    gen_by_topic = defaultdict(list)
    for q in generated_qs:
        gen_by_topic[q["topic"]].append(q)
        
    print("\n--- EVALUATING END-TO-END (BM25 + Template Match, Topic-Filtered) ---")
    
    sec_scores = defaultdict(list)
    detailed_report = defaultdict(list)
    
    for actual_q in actual_qs:
        topic = actual_q.get("topic")
        sec = actual_q.get("section")
        
        candidates = gen_by_topic.get(topic, [])
        if not candidates:
            continue
            
        actual_tokens = tokenize(actual_q.get("question_text", ""))
        actual_template = extract_template(actual_q.get("question_text", ""))
        
        corpus = [tokenize(c.get("question_text", "")) for c in candidates]
        bm25 = BM25Okapi(corpus)
        bm25_scores = bm25.get_scores(actual_tokens)
        
        # Normalize BM25
        max_bm25 = max(bm25_scores) if max(bm25_scores) > 0 else 1
        bm25_norm = [s / max_bm25 for s in bm25_scores]
        
        best_score = 0
        best_match = None
        
        for i, c in enumerate(candidates):
            gen_template = extract_template(c.get("question_text", ""))
            template_match = 1.0 if actual_template == gen_template else 0.0
            
            # Hybrid Score (70% BM25, 30% Template Match)
            score = (bm25_norm[i] * 0.7) + (template_match * 0.3)
            if score > best_score:
                best_score = score
                best_match = c
                
        sec_scores[sec].append(best_score)
        
        if best_match:
            detailed_report[sec].append({
                "actual": actual_q.get("question_text", ""),
                "topic": topic,
                "best_generated_match": best_match.get("question_text", ""),
                "score": round(best_score, 3)
            })
            
    total_score = 0
    total_qs = 0
    
    for sec, scores in sec_scores.items():
        if not scores: continue
        avg = sum(scores) / len(scores)
        total_score += sum(scores)
        total_qs += len(scores)
        print(f"\n--- Section: {sec} ---")
        print(f"  Matched Questions: {len(scores)}")
        print(f"  [{sec}] Average Score: {avg:.3f}")
        
    if total_qs > 0:
        final = total_score / total_qs
        print("\n============================================================")
        print(f"FULL END-TO-END PREDICTION ACCURACY (2026): {final:.3f}")
        print("============================================================")
        
    REPORT_PATH.parent.mkdir(parents=True, exist_ok=True)
    REPORT_PATH.write_text(json.dumps(detailed_report, indent=2), encoding="utf-8")
    print(f"\nDetailed evaluation report saved to -> {REPORT_PATH}")

if __name__ == "__main__":
    main()
